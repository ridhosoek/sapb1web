<?php

namespace App\Domain\Sap\Enums;

/**
 * SAP `AuthorizationStatus` of a Purchase Order and the portal policy for Goods Receipt PO (TD-01).
 *
 * Decision Q-20261109-03 (user): only a PO whose approval status is Generated (`WddStatus` P, Service Layer
 * `dasGenerated`) or Approved (`WddStatus` Y, `dasApproved`) may be received. Every other value, including a missing
 * or unknown one, is held. The rule applies to the Ready list, the cached Ready PO and the live read before each POST
 * on both the legacy and the partial-receipt path. It does not change any other portal document list. SAP stays the
 * final judge: PO 27871 (`dasApproved`) was still rejected by SAP, which this policy does not explain.
 */
enum PurchaseOrderAuthorization: string
{
    case Without = 'dasWithout';
    case Pending = 'dasPending';
    case Approved = 'dasApproved';
    case Rejected = 'dasRejected';
    case Generated = 'dasGenerated';
    case GeneratedByAuthorizer = 'dasGeneratedbyAuthorizer';
    case Cancelled = 'dasCancelled';

    /** @return list<self> */
    public static function receivable(): array
    {
        return [self::Generated, self::Approved];
    }

    /** @return list<string> Service Layer values that may be received, for filtering cached rows. */
    public static function receivableValues(): array
    {
        return array_map(fn (self $status): string => $status->value, self::receivable());
    }

    public static function allowsGoodsReceipt(mixed $sapValue): bool
    {
        return in_array(self::tryFrom(trim((string) $sapValue)), self::receivable(), true);
    }

    /** Operational explanation, or null when the status allows a Goods Receipt PO. */
    public static function holdReason(mixed $sapValue): ?string
    {
        if (self::allowsGoodsReceipt($sapValue)) {
            return null;
        }

        $value = trim((string) $sapValue);
        $rule = 'Hanya PO berstatus approval SAP Generated (P) atau Approved (Y) yang dapat diterima.';

        return match (self::tryFrom($value)) {
            self::Without => "PO tanpa proses approval di SAP (dasWithout) belum dapat diterima. {$rule}",
            self::GeneratedByAuthorizer => "Status approval SAP \"Generated by Authorizer\" belum dapat diterima. {$rule}",
            self::Pending => 'PO masih menunggu approval di SAP.',
            self::Rejected => 'Approval PO ditolak di SAP.',
            self::Cancelled => 'Approval PO dibatalkan di SAP.',
            default => $value === ''
                ? 'Status approval PO tidak terbaca dari SAP, sehingga PO ditahan sampai statusnya jelas.'
                : "Status approval SAP \"{$value}\" tidak dikenal portal, sehingga PO ditahan sampai statusnya jelas.",
        };
    }
}
